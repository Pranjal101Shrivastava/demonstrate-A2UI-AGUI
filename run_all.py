#!/usr/bin/env python3
"""Run every example's terminal walkthrough + the test suite, and record the real
output in docs/EXECUTION_LOG.md.      python run_all.py [filter]
"""
import datetime
import os
import platform
import subprocess
import sys
import time

from common.loader import ROOT, example_dirs, load


def main(filt=""):
    env = dict(os.environ, GENUX_LIVE="0", PYTHONIOENCODING="utf-8")
    out = [
        "# Execution log",
        "",
        f"Generated by `python run_all.py` on {datetime.date.today()} · Python {platform.python_version()} · "
        "scripted model (offline, deterministic). Every block below is the unedited stdout of "
        "`python <tech>/<mode>/example.py`.",
        "",
    ]
    failures = 0
    last_tech = None
    for d in example_dirs():
        rel = d.relative_to(ROOT).as_posix()
        if filt not in rel:
            continue
        tech = rel.split("/")[0]
        if tech != last_tech:
            out += [f"## {tech}", ""]
            last_tech = tech
        t0 = time.time()
        r = subprocess.run([sys.executable, str(d / "example.py")], capture_output=True, text=True, env=env, cwd=ROOT)
        ok = r.returncode == 0
        failures += not ok
        print(f"{'OK  ' if ok else 'FAIL'} {rel:<28} {time.time() - t0:.2f}s")
        m = load(d)
        out += [f"### {rel} — {m.MODE}", "", f"*{m.TITLE}*", "", f"```text\n$ python {rel}/example.py\n{r.stdout.rstrip()}" + (f"\n{r.stderr}" if not ok else "") + "\n```", ""]
    t = subprocess.run([sys.executable, "-m", "unittest", "discover", "-s", "tests", "-v"], capture_output=True, text=True, env=env, cwd=ROOT)
    print("unit tests:", "OK" if t.returncode == 0 else "FAIL")
    failures += t.returncode != 0
    out += ["## Test suite", "", "```text\n$ python -m unittest discover -s tests -v\n" + t.stderr.strip() + "\n```", ""]
    if not filt:
        (ROOT / "docs/EXECUTION_LOG.md").write_text("\n".join(out), encoding="utf-8")
        print("wrote docs/EXECUTION_LOG.md")
    return failures


if __name__ == "__main__":
    sys.exit(1 if main(sys.argv[1] if len(sys.argv) > 1 else "") else 0)
