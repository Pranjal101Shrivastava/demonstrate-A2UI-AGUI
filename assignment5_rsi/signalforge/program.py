"""The object being improved: a signal-controller *program*.

A program is stored as a small genome (which components are switched on, plus their
constants) and is always *rendered to real Python source*. The RSI methods edit the
genome, but everything downstream sees source code: the Budget RSI scorer reads the
textual diff between parent and child, the simulator runs the compiled ``decide``
function, and the labs print the code.

Components (each adds a helper function, a constant and a branch to ``decide``):

    actuated          end green early when the detector sees a gap of GAP_OUT seconds
                      (replaces the fixed-time rule ``elapsed >= FIXED_GREEN``)
    max_cap           force a switch once green has lasted MAX_GREEN seconds
    pressure          switch when the red queue exceeds PRESSURE_RATIO x the green queue
    starvation_guard  switch when a red-light vehicle has waited STARVE_LIMIT seconds
    skip_empty        never switch towards an empty cross street
"""
import hashlib
import random
from dataclasses import dataclass, field, replace

COMPONENTS = ("starvation_guard", "max_cap", "skip_empty", "pressure", "actuated")

# parameter -> (min, max, step, owning component or None for always-present)
PARAMS = {
    "min_green": (4, 30, 2, None),
    "fixed_green": (10, 60, 5, "!actuated"),   # only present when actuated is OFF
    "gap_out": (1, 8, 1, "actuated"),
    "max_green": (20, 90, 10, "max_cap"),
    "pressure_ratio": (1.0, 5.0, 0.5, "pressure"),
    "starve_limit": (20, 120, 10, "starvation_guard"),
}

CONST_NAMES = {p: p.upper() for p in PARAMS}


@dataclass(frozen=True)
class Program:
    on: frozenset = field(default_factory=frozenset)
    min_green: int = 8
    fixed_green: int = 30
    # Component constants start at deliberately poor, conservative values, the way a
    # new feature ships with "safe" defaults. A component only pays off once its
    # constant is tuned, so single first-order edits look worthless.
    gap_out: int = 6
    max_green: int = 90
    pressure_ratio: float = 4.0
    starve_limit: int = 120

    def active_params(self):
        out = []
        for p, (_, _, _, owner) in PARAMS.items():
            if owner is None or (owner.startswith("!") and owner[1:] not in self.on) or owner in self.on:
                out.append(p)
        return out

    @property
    def source(self):
        return render(self)

    @property
    def key(self):
        return hashlib.sha1(self.source.encode()).hexdigest()[:10]

    def summary(self):
        comps = "+".join(c for c in COMPONENTS if c in self.on) or "fixed-time"
        params = ", ".join(f"{p}={getattr(self, p)}" for p in self.active_params())
        return f"[{comps}] {params}"


SEED_PROGRAM = Program()   # plain fixed-time plan: 30 s green each way, min green 8 s


def _fmt(v):
    return f"{v:.1f}" if isinstance(v, float) else str(v)


def render(p):
    """Render a genome to readable Python source. Order is fixed so diffs are minimal."""
    L = ['"""Signal controller generated by SignalForge. decide(s) -> True means switch phase now."""', ""]
    for name in p.active_params():
        L.append(f"{CONST_NAMES[name]} = {_fmt(getattr(p, name))}")
    L.append("")
    helpers = {
        "starvation_guard": ["def starving(s):", "    return s['cross_wait'] >= STARVE_LIMIT"],
        "max_cap": ["def capped(s):", "    return s['elapsed'] >= MAX_GREEN"],
        "skip_empty": ["def cross_empty(s):", "    return s['cross_q'] == 0"],
        "pressure": ["def outweighed(s):", "    return s['cross_q'] > PRESSURE_RATIO * max(s['green_q'], 1)"],
        "actuated": ["def gapped_out(s):", "    return s['gap'] >= GAP_OUT"],
    }
    for c in COMPONENTS:
        if c in p.on:
            L += helpers[c] + ["", ""]
    L += ["def decide(s):", "    if s['elapsed'] < MIN_GREEN:", "        return False"]
    if "starvation_guard" in p.on:
        L += ["    if starving(s):", "        return True"]
    if "max_cap" in p.on:
        L += ["    if capped(s):", "        return True"]
    if "skip_empty" in p.on:
        L += ["    if cross_empty(s):", "        return False"]
    if "pressure" in p.on:
        L += ["    if outweighed(s):", "        return True"]
    if "actuated" in p.on:
        L += ["    return gapped_out(s)"]
    else:
        L += ["    return s['elapsed'] >= FIXED_GREEN"]
    return "\n".join(L) + "\n"


_COMPILED = {}


def compile_program(p):
    """exec() the rendered source (our own generated code) and return its decide()."""
    src = p.source
    fn = _COMPILED.get(src)
    if fn is None:
        ns = {}
        exec(compile(src, f"<controller {p.key}>", "exec"), ns)
        fn = _COMPILED[src] = ns["decide"]
    return fn


# ---------------------------------------------------------------------------------------
# Edit operators. Every edit has an operator key (used by SO-RSI's trace analysis), a
# human-readable description (what a coding agent would write in its commit message),
# and the child program.
# ---------------------------------------------------------------------------------------

@dataclass(frozen=True)
class Edit:
    op: tuple            # e.g. ("add", "starvation_guard") or ("increase", "min_green")
    desc: str
    parent: Program
    child: Program


def _clip(name, v):
    lo, hi, step, _ = PARAMS[name]
    v = min(hi, max(lo, v))
    return round(v, 1) if isinstance(step, float) else int(v)


def nudge(p, name, direction, steps=1):
    lo, hi, step, _ = PARAMS[name]
    old = getattr(p, name)
    new = _clip(name, old + direction * steps * step)
    child = replace(p, **{name: new})
    verb = "increase" if direction > 0 else "decrease"
    return Edit((verb, name), f"{verb} {name} {_fmt(old)}->{_fmt(new)}", p, child)


def toggle(p, comp):
    if comp in p.on:
        return Edit(("remove", comp), f"remove {comp}", p, replace(p, on=p.on - {comp}))
    return Edit(("add", comp), f"add {comp}", p, replace(p, on=p.on | {comp}))


def all_ops(p):
    """Every operator key that is legal on program p."""
    ops = [("remove" if c in p.on else "add", c) for c in COMPONENTS]
    for name in p.active_params():
        lo, hi, _, _ = PARAMS[name]
        v = getattr(p, name)
        if v < hi:
            ops.append(("increase", name))
        if v > lo:
            ops.append(("decrease", name))
    return ops


def apply_op(p, op, rng=None, steps=None):
    verb, target = op
    if verb in ("add", "remove"):
        return toggle(p, target)
    if steps is None:
        steps = rng.choice((1, 1, 2)) if rng else 1
    return nudge(p, target, 1 if verb == "increase" else -1, steps)


def random_edit(p, rng, weights=None, banned=()):
    """Sample an edit. weights: optional {op_key or verb or target: weight} preference map."""
    ops = [o for o in all_ops(p) if o not in banned]
    if not ops:
        ops = all_ops(p)
    if weights:
        w = [weights.get(o, weights.get(o[1], weights.get(o[0], 1.0))) for o in ops]
        op = rng.choices(ops, weights=w)[0]
    else:
        op = rng.choice(ops)
    return apply_op(p, op, rng)


def random_program(rng, depth=3, start=SEED_PROGRAM):
    p = start
    for _ in range(depth):
        p = random_edit(p, rng).child
    return p


def recombine(a, b, rng, prefer=None):
    """Child takes each component (with its constants) from one of the parents.

    prefer: optional dict component -> 'a'|'b' used by complementary recombination.
    """
    on = set()
    vals = {}
    for c in COMPONENTS:
        src = (prefer or {}).get(c) or rng.choice("ab")
        src_p = a if src == "a" else b
        if c in src_p.on:
            on.add(c)
        for name, (_, _, _, owner) in PARAMS.items():
            if owner == c:
                vals[name] = getattr(src_p, name)
    src_p = a if (prefer or {}).get("timing", rng.choice("ab")) == "a" else b
    vals["min_green"] = src_p.min_green
    vals["fixed_green"] = src_p.fixed_green
    return Program(on=frozenset(on), **vals)


def program_distance(a, b):
    """Hamming distance on components + normalised distance on shared constants."""
    d = len(a.on ^ b.on)
    for name, (lo, hi, _, _) in PARAMS.items():
        d += abs(getattr(a, name) - getattr(b, name)) / (hi - lo)
    return d
