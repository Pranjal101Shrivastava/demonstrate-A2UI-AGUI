#!/usr/bin/env python3
"""Run every Section-10 lab in order, then the tests, then rebuild the website.

    python run_all.py            # all 18 labs (~10 min on a laptop CPU) -> docs/EXECUTION_LOG.md
    python run_all.py 10_06      # only labs whose folder contains "10_06" (log not rewritten)
    RSI_FAST=1 python run_all.py # 2 seeds per experiment, for a quick smoke run

Every block in docs/EXECUTION_LOG.md is the unedited stdout of `python labs/<lab>/lab.py`.
"""
import datetime
import os
import platform
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def main(filt=""):
    env = dict(os.environ, PYTHONHASHSEED="0", PYTHONIOENCODING="utf-8")
    labs = sorted(p for p in (ROOT / "labs").iterdir() if (p / "lab.py").exists() and filt in p.name)
    out = ["# Execution log", "",
           f"Generated by `python run_all.py` on {datetime.date.today()} · Python {platform.python_version()} · "
           f"{platform.system()} · CPU only, standard library only. Every block below is the unedited stdout of "
           "`python labs/<lab>/lab.py`.", ""]
    failures, total = 0, time.time()
    for lab in labs:
        t0 = time.time()
        r = subprocess.run([sys.executable, str(lab / "lab.py")], capture_output=True, text=True, env=env, cwd=ROOT)
        ok = r.returncode == 0
        failures += not ok
        dt = time.time() - t0
        print(f"{'OK  ' if ok else 'FAIL'} {lab.name:<34} {dt:6.1f}s", flush=True)
        out += [f"## {lab.name}", "", f"`python labs/{lab.name}/lab.py` · {dt:.1f} s", "",
                "```text", r.stdout.rstrip() + (("\n" + r.stderr) if not ok else ""), "```", ""]
    t = subprocess.run([sys.executable, "-m", "unittest", "discover", "-s", "tests", "-v"],
                       capture_output=True, text=True, env=env, cwd=ROOT)
    print("unit tests:", "OK" if t.returncode == 0 else "FAIL")
    failures += t.returncode != 0
    out += ["## Test suite", "", "```text", "$ python -m unittest discover -s tests -v", t.stderr.strip(), "```", "",
            f"Total wall time: {time.time() - total:.0f} s", ""]
    if not filt:
        (ROOT / "docs" / "EXECUTION_LOG.md").write_text("\n".join(out), encoding="utf-8")
        print("wrote docs/EXECUTION_LOG.md")
        subprocess.run([sys.executable, str(ROOT / "build_site.py")], env=env, cwd=ROOT, check=False)
    return failures


if __name__ == "__main__":
    sys.exit(1 if main(sys.argv[1] if len(sys.argv) > 1 else "") else 0)
